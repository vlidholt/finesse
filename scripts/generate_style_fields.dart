// Generates the theme editor's table of every `StyleTokens` field:
// example/lib/common/theme_editor/style_fields.g.dart.
//
//   dart run scripts/generate_style_fields.dart          # write it
//   dart run scripts/generate_style_fields.dart --check  # exit 1 if stale
//
// Read from lib/src/theme/style.dart: each field of `StyleTokens` that its
// `copyWith` can set, with the first sentence of its documentation, a group
// (from its name) and the kind of control that edits it (from its type).
// The editor builds its "All settings" sections from the table, so a token
// added to the package shows up there without anyone remembering to.

import 'dart:io';

const _source = 'lib/src/theme/style.dart';
const _target = 'example/lib/common/theme_editor/style_fields.g.dart';

void main(List<String> args) {
  final check = args.contains('--check');
  final generated = generate(File(_source).readAsStringSync());
  final target = File(_target);
  if (check) {
    final current = target.existsSync() ? target.readAsStringSync() : '';
    if (!sameIgnoringWhitespace(current, generated)) {
      stderr.writeln(
        '$_target is stale: run dart run scripts/generate_style_fields.dart',
      );
      exit(1);
    }
    return;
  }
  target.writeAsStringSync(generated);
  // Formatted as the rest of the example is, which CI checks.
  Process.runSync('dart', ['format', _target]);
  stdout.writeln('wrote $_target');
}

/// Whether [a] and [b] are the same source, however `dart format` wrapped
/// them.
bool sameIgnoringWhitespace(String a, String b) {
  final space = RegExp(r'\s+');
  // A trailing comma comes and goes with the wrapping.
  String plain(String s) =>
      s.replaceAll(space, '').replaceAll(',)', ')').replaceAll(',]', ']');
  return plain(a) == plain(b);
}

/// The table's source for the text of `style.dart`.
String generate(String style) {
  final start = style.indexOf('class StyleTokens {');
  final end = style.indexOf('  static const ', start);
  final body = style.substring(start, end);
  final copyWith = style.substring(
    style.indexOf('StyleTokens copyWith({'),
    style.indexOf('}) {', style.indexOf('StyleTokens copyWith({')),
  );
  final settable = {
    for (final m in RegExp(
      r'^\s+[\w<>?]+\s+(\w+),',
      multiLine: true,
    ).allMatches(copyWith))
      m[1]!,
  };

  final fields = <_Field>[];
  final lines = body.split('\n');
  final doc = <String>[];
  for (final line in lines) {
    final trimmed = line.trim();
    if (trimmed.startsWith('///')) {
      doc.add(trimmed.substring(3).trim());
      continue;
    }
    final field = RegExp(r'^  final ([\w<>?]+) (\w+);$').firstMatch(line);
    if (field != null) {
      final type = field[1]!;
      final name = field[2]!;
      final kind = _kindOf(type, name);
      if (kind != null && settable.contains(name)) {
        fields.add(
          _Field(
            name: name,
            type: type,
            kind: kind,
            group: _groupOf(name),
            doc: _firstSentence(doc),
          ),
        );
      }
    }
    if (!trimmed.startsWith('@')) doc.clear();
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by scripts/generate_style_fields.dart from')
    ..writeln('// lib/src/theme/style.dart. Do not edit by hand.')
    ..writeln()
    ..writeln("import 'package:example/common/theme_editor/style_field.dart';")
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import 'package:una/una.dart';")
    ..writeln()
    ..writeln('/// Every `StyleTokens` field the editor can set, in the order')
    ..writeln('/// `StyleTokens` declares them.')
    ..writeln('final styleFields = <StyleField>[');
  for (final f in fields) {
    final nullable = f.type.endsWith('?');
    final bare = nullable ? f.type.substring(0, f.type.length - 1) : f.type;
    out
      ..writeln('  StyleField(')
      ..writeln("    name: '${f.name}',")
      ..writeln('    group: StyleFieldGroup.${f.group},')
      ..writeln('    kind: StyleFieldKind.${f.kind},')
      ..writeln(nullable ? '    nullable: true,' : '')
      ..writeln('    doc: ${_dartString(f.doc)},')
      ..writeln('    read: (t) => t.${f.name},')
      ..writeln(
        '    write: (t, v) => t.copyWith(${f.name}: v as $bare),',
      )
      ..writeln('  ),');
  }
  out.writeln('];');
  // Drop the blank lines the optional `nullable:` leaves.
  return out.toString().replaceAll(RegExp(r'\n\n(?=    )'), '\n');
}

class _Field {
  _Field({
    required this.name,
    required this.type,
    required this.kind,
    required this.group,
    required this.doc,
  });

  final String name;
  final String type;
  final String kind;
  final String group;
  final String doc;
}

/// The control that edits a field of [type], or null for one the editor
/// leaves alone (the name, the phone metrics, the radius scale).
String? _kindOf(String type, String name) {
  final bare = type.replaceAll('?', '');
  return switch (bare) {
    'double' when name.contains('Opacity') || name.contains('Strength') =>
      'fraction',
    'double' => 'number',
    'bool' => 'toggle',
    'RadiusToken' => 'radius',
    'SurfaceFill' => 'fill',
    'List<BoxShadow>' => 'shadow',
    'TextRole' => 'textRole',
    'Motion' => 'motion',
    _ => null,
  };
}

/// The section a field is listed in, by its name: the first rule that
/// matches.
String _groupOf(String name) {
  bool starts(List<String> prefixes) => prefixes.any(name.startsWith);
  const type = {
    'title', 'label', 'body', 'caption', 'overline', 'field', 'display', //
    'headline', 'subtitle', 'small',
  };
  if (type.contains(name) || name.startsWith('iconOptical')) return 'type';
  if (name.contains('Opacity') && !name.startsWith('bottomNavigation') ||
      starts(['glass', 'cardBlur', 'floatingShadow'])) {
    return 'glass';
  }
  if (starts(['page', 'gap', 'divider', 'radius', 'surfaceRadius'])) {
    return 'layout';
  }
  if (starts(['ring', 'motion'])) return 'focusMotion';
  if (starts([
    'button', 'iconButton', 'outlineButton', 'secondaryButton', 'link', //
    'controlShadow', 'toggle', 'fab',
  ])) {
    return 'buttons';
  }
  if (starts([
    'input', 'textarea', 'underlinedFields', 'fieldFill', //
    'fieldBorderless', 'select', 'kbd',
  ])) {
    return 'fields';
  }
  if (starts(['checkbox', 'radio', 'switch', 'slider', 'control'])) {
    return 'controls';
  }
  if (starts(['card', 'dialog', 'sheet', 'popover', 'tooltip', 'alert'])) {
    return 'surfaces';
  }
  if (starts(['menu', 'item', 'command'])) return 'menus';
  if (starts([
    'appBar', 'navigation', 'bottomNavigation', 'sidebar', 'tab', //
    'concentricTabs', 'underlineTab', 'accordion',
  ])) {
    return 'navigation';
  }
  return 'content';
}

/// The first sentence of a doc comment, as plain text.
String _firstSentence(List<String> doc) {
  final text = doc
      .takeWhile((line) => line.isNotEmpty)
      .join(' ')
      .replaceAllMapped(RegExp(r'\[([^\]]+)\]'), (m) => m[1]!)
      .replaceAll('`', '');
  final end = RegExp(r'[.:](\s|$)').firstMatch(text);
  final sentence = end == null ? text : text.substring(0, end.start + 1);
  return sentence.endsWith(':')
      ? '${sentence.substring(0, sentence.length - 1)}.'
      : sentence;
}

String _dartString(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}
